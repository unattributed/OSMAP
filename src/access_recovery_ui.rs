//! Local, server-rendered recovery pages. No remote QR service or client secrets.
use crate::browser_access::{AccessError, AccessView};
use crate::html::TrustedHtml;
use crate::http_support::escape_html;
use crate::totp_enrollment::PendingEnrollment;
use qrcodegen::{QrCode, QrCodeEcc};
use std::fmt::Write;

fn hidden(name: &str, value: &str) -> String {
    format!(
        "<input type=\"hidden\" name=\"{name}\" value=\"{}\">",
        escape_html(value)
    )
}
fn form(path: &str, csrf: &str, action: &str, fields: &str, button: &str) -> String {
    format!("<form method=\"post\" action=\"{path}\" autocomplete=\"off\">{}{}<fieldset><legend>Confirm this step</legend>{fields}<button type=\"submit\">{button}</button></fieldset></form>", hidden("csrf_token", csrf), hidden("action", action))
}
fn otp(name: &str, label: &str) -> String {
    format!("<label for=\"{name}\">{label}</label><input id=\"{name}\" name=\"{name}\" type=\"text\" inputmode=\"numeric\" autocomplete=\"one-time-code\" pattern=\"[0-9]{{6}}\" minlength=\"6\" maxlength=\"6\" required>")
}
fn password(name: &str, label: &str, fresh: bool) -> String {
    format!("<label for=\"{name}\">{label}</label><input id=\"{name}\" name=\"{name}\" type=\"password\" autocomplete=\"{}\"{} required>", if fresh { "new-password" } else { "current-password" }, if fresh { " minlength=\"15\" maxlength=\"128\"" } else { " maxlength=\"1024\"" })
}

fn enrollment(pending: &PendingEnrollment) -> Result<String, AccessError> {
    if pending.id.len() != 64
        || !pending
            .id
            .bytes()
            .all(|v| v.is_ascii_digit() || (b'a'..=b'f').contains(&v))
        || pending.revision == 0
        || !(16..=128).contains(&pending.secret_base32.len())
        || !pending
            .secret_base32
            .bytes()
            .all(|v| v.is_ascii_uppercase() || (b'2'..=b'7').contains(&v))
        || !pending.otpauth_uri.starts_with("otpauth://totp/")
        || pending.otpauth_uri.len() > 2048
    {
        return Err(AccessError::Unavailable);
    }
    let code = QrCode::encode_text(&pending.otpauth_uri, QrCodeEcc::Medium)
        .map_err(|_| AccessError::Unavailable)?;
    let extent = code.size() + 8;
    let mut modules = String::new();
    for y in 0..code.size() {
        for x in 0..code.size() {
            if code.get_module(x, y) {
                // Only bounded integers generated by the QR encoder enter SVG.
                write!(modules, "M{},{}h1v1h-1z ", x + 4, y + 4)
                    .map_err(|_| AccessError::Unavailable)?;
            }
        }
    }
    Ok(format!("<section aria-labelledby=\"enrollment-heading\"><h2 id=\"enrollment-heading\">Add the new authenticator</h2><p>Scan this QR code in your authenticator app. Keep this page private.</p><svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 {extent} {extent}\" width=\"320\" height=\"320\" role=\"img\" aria-label=\"New authenticator QR code\" style=\"max-width:100%;height:auto;background:white\"><rect width=\"100%\" height=\"100%\" fill=\"white\"/><path d=\"{modules}\" fill=\"black\"/></svg><details><summary>Enter a setup key instead</summary><p>Use this key with a time-based, six-digit authenticator:</p><code>{}</code></details><p>Enter a current six-digit code from the <strong>new</strong> entry to confirm it. The QR code alone does not activate the replacement.</p></section>", escape_html(&pending.secret_base32)))
}
fn enrollment_fields(pending: &PendingEnrollment) -> String {
    format!(
        "{}{}",
        hidden("enrollment_id", &pending.id),
        hidden("revision", &pending.revision.to_string())
    )
}

pub(crate) fn render_access_page(
    view: &AccessView,
    notice: Option<&str>,
) -> Result<TrustedHtml, AccessError> {
    let (heading, content, header) = match view {
        AccessView::RecoveryEmail { csrf } => (
            "Recover access",
            format!("<p>Enter your login email address. If recovery is available, we will email a code to the address registered for recovery.</p>{}", form("/recover", csrf, "send_code", "<label for=\"email\">Login email address</label><input id=\"email\" name=\"email\" type=\"email\" autocomplete=\"username\" maxlength=\"254\" required>", "Email a recovery code")),
            String::new(),
        ),
        AccessView::RecoveryCode { csrf, challenge_id } => (
            "Check your email",
            format!("<p>If recovery is available for that account, a code has been sent. Enter the latest code before it expires.</p>{}", form("/recover", csrf, "verify_code", &format!("{}{}", hidden("challenge_id", challenge_id), otp("code", "Six-digit email code")), "Verify email code")),
            String::new(),
        ),
        AccessView::RecoverySetup { csrf, enrollment: pending } => (
            "Restore access",
            format!("<p>Choose a new password and confirm your replacement authenticator. You will sign in again after the update is confirmed.</p>{}{}", enrollment(pending)?, form("/recover/setup", csrf, "confirm_recovery", &format!("{}{}{}{}<p>Use 15–128 characters.</p>", enrollment_fields(pending), password("new_password", "New password", true), password("confirmation", "Confirm new password", true), otp("new_totp_code", "Code from the new authenticator")), "Verify and restore access")),
            String::new(),
        ),
        AccessView::TotpResetStart { account, csrf } => (
            "Replace your authenticator",
            format!("<p>Confirm your current password and a fresh code from your current authenticator before creating a replacement.</p>{}", form("/settings/authenticator", csrf, "begin_reset", &format!("{}{}", password("current_password", "Current password", false), otp("current_totp_code", "Current authenticator code")), "Create replacement authenticator")),
            crate::http_ui::app_header(account, csrf, "settings-authentication"),
        ),
        AccessView::TotpReplacement { account, csrf, enrollment: pending } => (
            "Confirm your replacement authenticator",
            format!("<p>Your current authenticator remains in use until the replacement is verified and activation is confirmed.</p>{}{}", enrollment(pending)?, form("/settings/authenticator", csrf, "confirm_reset", &format!("{}{}", enrollment_fields(pending), otp("new_totp_code", "Code from the new authenticator")), "Verify and activate replacement")),
            crate::http_ui::app_header(account, csrf, "settings-authentication"),
        ),
        AccessView::Complete => (
            "Access updated",
            "<p>The update was confirmed. Sign in with your password and your new authenticator.</p><a class=\"button-link\" href=\"/login\">Sign in</a>".into(),
            String::new(),
        ),
    };
    let notice = notice.map_or_else(String::new, |v| {
        format!("<p role=\"status\">{}</p>", escape_html(v))
    });
    Ok(TrustedHtml::from_template(format!("{header}<main id=\"main-content\" class=\"page-shell standalone-notice\" tabindex=\"-1\"><section class=\"panel\"><h1>{heading}</h1>{notice}{content}<p><a href=\"/login\">Return to sign in</a></p></section></main>")))
}

pub(crate) fn render_access_failure(message: &str) -> TrustedHtml {
    TrustedHtml::from_template(format!("<main id=\"main-content\" class=\"page-shell standalone-notice\"><section class=\"panel\"><h1>Recovery unavailable</h1><p role=\"status\">{}</p><a href=\"/login\">Return to sign in</a></section></main>", escape_html(message)))
}
